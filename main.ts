// main.ts — SOLMAR HEAT's entry program (Node 22, standard library only).
// Copies the static game and its screenshots to /output and writes the
// dossier with the kit's buildDossier, byte for byte as the scorer rebuilds
// it. Two runs write the same bytes: the copies are file copies and the
// dossier is deterministic for a fixed tree.
// Round-2 fix: never delete the output dir itself — the grader mounts it,
// and removing a mount point fails EBUSY; mkdir + cpSync like the kit starter.

import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-game.ts';

const repoRoot = dirname(fileURLToPath(import.meta.url));
const outDir = process.env.MAKEFUN_OUTPUT_DIR || '/output';

mkdirSync(outDir, { recursive: true });
cpSync(join(repoRoot, 'game'), join(outDir, 'game'), { recursive: true });
mkdirSync(join(outDir, 'screenshots'), { recursive: true });
if (existsSync(join(repoRoot, 'screenshots'))) cpSync(join(repoRoot, 'screenshots'), join(outDir, 'screenshots'), { recursive: true });

writeFileSync(
  join(outDir, 'dossier.json'),
  buildDossier(outDir, {
    text_max_bytes: 163840,
    screenshots: { max: 4, max_bytes: 262144 },
    game_max_files: 993,
    game_max_bytes: 50331648,
    game_path_max_bytes: 1000,
  })
);
